using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using System.Text.Json.Serialization;
using Microsoft.EntityFrameworkCore;

namespace LANCommander.Server.Data.Models
{
    /// <summary>
    /// One thing that happened in a match, exactly as a reporter sent it: a kill, a completed lap, a
    /// defeated player. Events are facts and are never edited.
    /// </summary>
    /// <remarks>
    /// Deliberately not a <see cref="BaseModel"/>: events are written in bulk by one writer, so they skip
    /// the audit columns and their foreign keys.
    /// </remarks>
    [Table("MatchEvents")]
    [Index(nameof(MatchId), nameof(GameTimeMilliseconds))]
    [Index(nameof(MatchId), nameof(Type))]
    [Index(nameof(ReporterId), nameof(Sequence), IsUnique = true)]
    public class MatchEvent
    {
        /// <summary>Generated by the reporter when the event happened and reused on every retry.</summary>
        [Key]
        [DatabaseGenerated(DatabaseGeneratedOption.None)]
        public Guid Id { get; set; }

        public Guid MatchId { get; set; }
        [JsonIgnore]
        [ForeignKey(nameof(MatchId))]
        [InverseProperty(nameof(Models.Match.Events))]
        public Match? Match { get; set; }

        public Guid ReporterId { get; set; }
        [JsonIgnore]
        [ForeignKey(nameof(ReporterId))]
        [InverseProperty(nameof(MatchReporter.Events))]
        public MatchReporter? Reporter { get; set; }

        /// <summary>The reporter's number for the event, starting at 1 and increasing by 1.</summary>
        public long Sequence { get; set; }

        /// <summary>What happened: <c>kill</c>, <c>lap_completed</c>, <c>player_defeated</c>.</summary>
        [MaxLength(64)]
        public string Type { get; set; } = "";

        /// <summary>Milliseconds of game time since the reporter saw the match start.</summary>
        public long GameTimeMilliseconds { get; set; }

        /// <summary>The game's simulation tick, when it has one.</summary>
        public long? Tick { get; set; }

        /// <summary>The <see cref="MatchParticipant.PlayerKey"/> of who caused the event.</summary>
        [MaxLength(191)]
        public string? ActorKey { get; set; }

        /// <summary>The <see cref="MatchParticipant.PlayerKey"/> of who it happened to, such as a kill's victim.</summary>
        [MaxLength(191)]
        public string? SubjectKey { get; set; }

        /// <summary>The game-specific detail of the event, as a JSON object.</summary>
        public string? Payload { get; set; }

        /// <summary>The reporter's clock when the event happened. Informational only.</summary>
        public DateTime? ClientTime { get; set; }

        /// <summary>When the LANCommander server received the event.</summary>
        public DateTime ReceivedOn { get; set; }
    }
}
